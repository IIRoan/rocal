import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.join(import.meta.dir, "..");
const entry = path.join(root, "src/webview/entry.ts");
const output = path.join(root, "src/generated/webview-script.ts");
const check = process.argv.includes("--check");

const result = await Bun.build({
  entrypoints: [entry],
  target: "browser",
  format: "iife",
  minify: true,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const [bundle] = result.outputs;
if (!bundle) throw new Error("The editor bundle produced no output.");
// The page inlines the bundle in a script element, which any `</script` inside it would end early.
const code = (await bundle.text()).replace(/<\/(script)/gi, "<\\/$1");
const source = `// Generated by packages/mail-editor/scripts/build-webview-script.ts from src/webview/entry.ts; run \`bun run build:webview\` there.\nexport const MAIL_EDITOR_WEBVIEW_SCRIPT = ${JSON.stringify(code)};\n`;

if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== source) {
    console.error("packages/mail-editor/src/generated/webview-script.ts is stale; run `bun run build:webview` in packages/mail-editor.");
    process.exit(1);
  }
} else {
  await writeFile(output, source);
  console.log(`Wrote ${path.relative(process.cwd(), output)} (${Math.round(source.length / 1024)} KiB).`);
}
